// Draws text at (x, y); mirror flips the whole string (e.g. a sign seen from behind).
function sign(p, x, y, text, color, mirror = false) {
  const chars = [...text];
  chars.forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) return;
    const gx = mirror ? x + (chars.length - 1 - i) * 4 : x + i * 4;
    glyph.forEach((row, j) => [...row].forEach((c, k) => {
      if (c === '#') p.px(mirror ? gx + 2 - k : gx + k, y + j, color);
    }));
  });
  return p;
}

const width = text => text.length * 4 - 1;

module.exports = { sign, width };
